// Generates the multiplane scene silhouettes in public/planes/.
// Each SVG is a single-colour mask; the page paints it with a theme token.
// Run: node scripts/generate-planes.mjs
import { writeFileSync } from 'node:fs';

const W = 1600;
const H = 900;
let seed = 0x85c69401;
const rand = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 2 ** 32);
const r = (a, b) => a + rand() * (b - a);
const f = (n) => n.toFixed(1);

function ridge(baseY, amp, step, octaves) {
  const pts = [];
  const phases = octaves.map(() => r(0, Math.PI * 2));
  for (let x = -20; x <= W + 20; x += step) {
    let y = baseY;
    octaves.forEach(([freq, a], i) => (y += Math.sin(x * freq + phases[i]) * amp * a));
    y += r(-amp * 0.04, amp * 0.04);
    pts.push([x, y]);
  }
  return pts;
}

function pine(cx, baseY, h, w) {
  // tiered conifer: a stack of jagged skirts, drawn as one closed outline
  const tiers = Math.max(3, Math.round(h / (w * 0.55)));
  const left = [];
  const right = [];
  const top = baseY - h;
  for (let i = 0; i < tiers; i++) {
    const t0 = i / tiers;
    const t1 = (i + 1) / tiers;
    const yTop = top + h * t0 * 0.92;
    const yBot = top + h * t1 * 0.92;
    const half = (w / 2) * (0.25 + 0.75 * t1) * r(0.88, 1.08);
    const inner = half * 0.55;
    left.push([cx - inner * (i === 0 ? 0 : 1), yTop + (i === 0 ? 0 : h * 0.02)], [cx - half, yBot + r(0, h * 0.02)]);
    right.push([cx + inner * (i === 0 ? 0 : 1), yTop + (i === 0 ? 0 : h * 0.02)], [cx + half, yBot + r(0, h * 0.02)]);
  }
  const trunkW = Math.max(2, w * 0.06);
  const pts = [[cx, top - h * 0.03], ...right, [cx + trunkW, baseY - h * 0.08], [cx + trunkW, baseY + 4], [cx - trunkW, baseY + 4], [cx - trunkW, baseY - h * 0.08], ...left.reverse()];
  return 'M' + pts.map(([x, y]) => `${f(x)} ${f(y)}`).join('L') + 'Z';
}

function groundPath(pts) {
  return 'M' + pts.map(([x, y]) => `${f(x)} ${f(y)}`).join('L') + `L${W + 20} ${H}L-20 ${H}Z`;
}

function yAt(pts, x) {
  for (let i = 1; i < pts.length; i++) if (pts[i][0] >= x) {
    const [x0, y0] = pts[i - 1];
    const [x1, y1] = pts[i];
    return y0 + ((x - x0) / (x1 - x0)) * (y1 - y0);
  }
  return pts.at(-1)[1];
}

function forest({ baseY, amp, minH, maxH, density, gap }) {
  const ground = ridge(baseY, amp, 24, [[0.004, 1], [0.011, 0.35]]);
  const paths = [groundPath(ground)];
  for (let x = -30; x < W + 30; x += r(density * 0.5, density * 1.1)) {
    if (gap && x > gap[0] && x < gap[1]) continue;
    const h = r(minH, maxH);
    paths.push(pine(x, yAt(ground, x) + r(2, 10), h, h * r(0.32, 0.42)));
  }
  return paths;
}

function svg(name, paths, note) {
  const body = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMax slice">\n<!-- ${note}. Generated by scripts/generate-planes.mjs (seeded, deterministic). -->\n<path fill="#000" d="${paths.join('')}"/>\n</svg>\n`;
  writeFileSync(new URL(`../public/planes/${name}.svg`, import.meta.url), body);
  console.log(name, (body.length / 1024).toFixed(1) + 'KB');
}

// Far mountain ridge
svg('ridge', [groundPath(ridge(430, 120, 16, [[0.0021, 1], [0.0067, 0.45], [0.019, 0.12]]))], 'Plane 1: far mountain ridge');
// Second ridge, closer and lower
svg('hills', [groundPath(ridge(540, 70, 16, [[0.0033, 1], [0.009, 0.4], [0.024, 0.1]]))], 'Plane 2: near ridge');
// Far pines
svg('far', forest({ baseY: 640, amp: 26, minH: 40, maxH: 90, density: 22 }), 'Plane 3: far pine line');
// Mid pines, with a clearing on the right for the cottage
svg('mid', forest({ baseY: 740, amp: 30, minH: 110, maxH: 230, density: 46, gap: [1060, 1290] }), 'Plane 4: mid forest');
// Near plane: tall framing pines on the edges plus undergrowth
{
  const ground = ridge(860, 18, 20, [[0.006, 1], [0.03, 0.4]]);
  const paths = [groundPath(ground)];
  for (const [x, h] of [[-40, 820], [70, 640], [170, 470], [1440, 560], [1540, 780], [1650, 900]]) {
    paths.push(pine(x, H + 10, h, h * 0.36));
  }
  // fern fronds along the floor
  for (let x = -10; x < W + 10; x += r(14, 30)) {
    const y = yAt(ground, x) + 6;
    const len = r(26, 60);
    const lean = r(-0.5, 0.5);
    paths.push(`M${f(x - 3)} ${f(y)}Q${f(x + lean * len * 0.6)} ${f(y - len * 0.6)} ${f(x + lean * len)} ${f(y - len)}Q${f(x + lean * len * 0.4 + 4)} ${f(y - len * 0.5)} ${f(x + 3)} ${f(y)}Z`);
  }
  svg('near', paths, 'Plane 5: nearest framing pines and ferns');
}
